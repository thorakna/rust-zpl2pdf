"""Generates crates/zpl2pdf/src/font/font0_metrics.rs from the measured
advance widths in tools/calibration/font0_advances.json (produced by
tools/calibration/measure_font0b.py)."""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(ROOT, 'tools', 'calibration', 'font0_advances.json')
dst = os.path.join(ROOT, 'crates', 'zpl2pdf', 'src', 'font', 'font0_metrics.rs')
d = json.load(open(src, encoding='utf-8'))
items = sorted((ord(k), v) for k, v in d.items())
lines = [
    '//! Advance widths of Zebra font 0, measured against Labelary.',
    '//!',
    '//! Generated by `tools/gen_font0_metrics.py` from',
    '//! `tools/calibration/font0_advances.json`. Each entry is the advance of a',
    '//! character as a fraction of the `^A0` width parameter.',
    '',
    '/// `(code point, advance / width)`, sorted by code point.',
    'pub const FONT0_ADVANCES: &[(u32, f32)] = &[',
]
lines += [f'    (0x{cp:04X}, {v:.4f}),' for cp, v in items]
lines.append('];')
open(dst, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print(f'{len(items)} entries written to {dst}')
